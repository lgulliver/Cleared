#!/usr/bin/env python3
"""Generate Cleared/Data.lua from wago.tools DB2 exports.

Usage: python3 tools/gen_data.py [--build 1.60.1.70938] [--out PATH] [--skip-check]

Without --build, the newest WoW Forever ("wowf") build listed by wago.tools is used.
After writing, tools/check_data.lua is run to verify Overrides.lua against the new data.
"""

import argparse
import csv
import io
import json
import os
import shutil
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "Cleared", "Data.lua")
CHECKER = os.path.join(ROOT, "tools", "check_data.lua")
BUILDS_URL = "https://wago.tools/api/builds"
TABLE_URL = "https://wago.tools/db2/{table}/csv?build={build}"
PRODUCT = "wowf"

# Map 0 holds world bosses; 13 and 2720 (The Searing Basin, boss "Testwerk") are test maps.
EXCLUDED_MAPS = {0, 13, 2720}

# Map.InstanceType: 1 = dungeon, 2 = raid.
INSTANCE_TYPES = {"1", "2"}

# Regular 5-man rows use 0 or 1 (BFD and Gnomeregan split bosses across both); 198/201/215 are SoD.
DIFFICULTIES = {"0", "1"}


def filter_data(map_rows, enc_rows):
    """Return {mapID: {"name", "raid", "encounters": [{"id", "name", "order", "flags"}]}} for dungeons and raids."""
    dungeons = {}
    for row in map_rows:
        map_id = int(row["ID"])
        if row.get("InstanceType") not in INSTANCE_TYPES or map_id in EXCLUDED_MAPS or not row.get("MapName_lang"):
            continue
        dungeons[map_id] = {"name": row["MapName_lang"], "raid": row["InstanceType"] == "2", "encounters": []}

    for row in enc_rows:
        map_id = int(row["MapID"])
        if row["DifficultyID"] not in DIFFICULTIES or map_id not in dungeons:
            continue
        dungeons[map_id]["encounters"].append(
            {
                "id": int(row["ID"]),
                "name": row["Name_lang"],
                "order": int(row["OrderIndex"]),
                "flags": int(row["Flags"]),
            }
        )

    for d in dungeons.values():
        d["encounters"].sort(key=lambda x: (x["order"], x["id"]))
    return {k: v for k, v in dungeons.items() if v["encounters"]}


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_lua(data, build):
    lines = [
        f"-- Generated by tools/gen_data.py from wago.tools build {build}. Do not edit.",
        "local _, ns = ...",
        "",
        f"ns.Build = {lua_string(build)}",
        "",
        "ns.Dungeons = {",
    ]
    for map_id in sorted(data):
        d = data[map_id]
        ids = ", ".join(str(x["id"]) for x in d["encounters"])
        raid = " raid = true," if d["raid"] else ""
        lines.append(f"\t[{map_id}] = {{ name = {lua_string(d['name'])},{raid} encounters = {{ {ids} }} }},")
    lines += ["}", "", "ns.Encounters = {"]
    encounters = sorted(((x["id"], map_id, x) for map_id, d in data.items() for x in d["encounters"]))
    for enc_id, map_id, x in encounters:
        lines.append(
            f"\t[{enc_id}] = {{ map = {map_id}, name = {lua_string(x['name'])}, order = {x['order']}, flags = {x['flags']} }},"
        )
    lines += ["}", ""]
    return "\n".join(lines)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Cleared-gen_data"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    builds = json.loads(fetch(BUILDS_URL))
    return builds[PRODUCT][0]["version"]


def fetch_table(table, build):
    return list(csv.DictReader(io.StringIO(fetch(TABLE_URL.format(table=table, build=build)))))


def run_check():
    luajit = shutil.which("luajit")
    if not os.path.exists(CHECKER):
        print("warning: tools/check_data.lua not found, skipping override check", file=sys.stderr)
        return 0
    if not luajit:
        print("error: luajit not on PATH, cannot run tools/check_data.lua", file=sys.stderr)
        return 1
    return subprocess.run([luajit, CHECKER], cwd=ROOT).returncode


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", help="wago.tools build version (default: newest wowf build)")
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--skip-check", action="store_true")
    args = parser.parse_args(argv)

    build = args.build or latest_build()
    data = filter_data(fetch_table("Map", build), fetch_table("DungeonEncounter", build))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_lua(data, build))
    count = sum(len(d["encounters"]) for d in data.values())
    print(f"wrote {args.out}: {len(data)} dungeons, {count} encounters (build {build})")

    return 0 if args.skip_check else run_check()


if __name__ == "__main__":
    sys.exit(main())
